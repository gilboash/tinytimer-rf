# PlatformIO pre-build step: pack ../web/* into src/web_assets.h as gzipped
# byte arrays so the base serves the UI from its own flash (no filesystem image
# to upload). Re-runs on every build, so edits in web/ are picked up.
import gzip, os
Import("env")

PROJ = env["PROJECT_DIR"]
WEB = os.path.join(os.path.dirname(PROJ), "web")
OUT = os.path.join(PROJ, "src", "web_assets.h")
FILES = [("/", "index.html", "text/html"), ("/index.html", "index.html", "text/html"),
         ("/gate", "gate.html", "text/html"), ("/base", "base.html", "text/html"),
         ("/app.js", "app.js", "text/javascript"), ("/app.css", "app.css", "text/css"),
         ("/race.js", "race.js", "text/javascript"), ("/race.css", "race.css", "text/css"),
         ("/announcer.js", "announcer.js", "text/javascript"), ("/beep.js", "beep.js", "text/javascript"),
         ("/nosleep.js", "nosleep.js", "text/javascript"), ("/nosleep.mp4", "nosleep.mp4", "video/mp4"),
         ("/breaking_carbon.jpg", "breaking_carbon.jpg", "image/jpeg")]

blobs, lines = {}, ["// generated by embed_web.py from ../web: do not edit", "#pragma once", "#include <Arduino.h>",
                    "struct WebAsset { const char *path, *mime; const uint8_t *data; size_t len; };"]
for _, fn, _ in FILES:
    if fn not in blobs:
        with open(os.path.join(WEB, fn), "rb") as f:
            blobs[fn] = gzip.compress(f.read(), 9, mtime=0)
        var = "web_" + fn.replace(".", "_")
        lines.append("static const uint8_t %s[] PROGMEM = {%s};" % (var, ",".join(str(b) for b in blobs[fn])))
lines.append("static const WebAsset WEB_ASSETS[] = {")
for path, fn, mime in FILES:
    lines.append('  {"%s", "%s", web_%s, %d},' % (path, mime, fn.replace(".", "_"), len(blobs[fn])))
lines.append("};")
lines.append("static const size_t WEB_ASSET_COUNT = sizeof(WEB_ASSETS) / sizeof(WEB_ASSETS[0]);")
new = "\n".join(lines) + "\n"
if not os.path.exists(OUT) or open(OUT).read() != new:
    with open(OUT, "w") as f:
        f.write(new)
